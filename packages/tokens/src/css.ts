import { duration, easing, font } from "@/motion";
import { themes } from "@/themes";
import type { Palette, Shape, Theme } from "@/types";

const block = (selector: string, vars: Record<string, string>) =>
	`${selector} {\n${Object.entries(vars)
		.map(([k, v]) => `\t--zupy-${k}: ${v};`)
		.join("\n")}\n}`;

const paletteVars = (p: Palette) => ({ ...p }) as Record<string, string>;

const shapeVars = (s: Shape) => ({
	"edge-width": s.edgeWidth,
	lift: s.lift,
	press: s.press,
	gloss: String(s.gloss),
	"radius-sm": s.radius.sm,
	"radius-md": s.radius.md,
	"radius-lg": s.radius.lg,
	"radius-xl": s.radius.xl,
});

const staticVars = {
	...Object.fromEntries(
		Object.entries(easing).map(([k, v]) => [`ease-${k}`, v]),
	),
	...Object.fromEntries(
		Object.entries(duration).map(([k, v]) => [`duration-${k}`, v]),
	),
	...Object.fromEntries(Object.entries(font).map(([k, v]) => [`font-${k}`, v])),
};

/**
 * Theme is picked with `data-theme="<name>"` on any element; `pop` is the default on `:root`.
 * Dark mode is the `.dark` class, on the same element or an ancestor.
 */
function themeCss(theme: Theme, isDefault: boolean) {
	const t = `[data-theme="${theme.name}"]`;
	const light = isDefault ? `:root,\n${t}` : t;
	const dark = isDefault
		? `.dark,\n${t}.dark,\n.dark ${t}`
		: `${t}.dark,\n.dark ${t},\n${t} .dark`;
	return [
		block(light, { ...paletteVars(theme.light), ...shapeVars(theme.shape) }),
		block(dark, paletteVars(theme.dark)),
	].join("\n\n");
}

/** Raw `--zupy-*` custom properties for every theme. Framework agnostic. */
export function toCss() {
	const [first, ...rest] = Object.values(themes);
	if (!first) return "";
	return [
		"/* Generated by @zupy/tokens. Do not edit. */",
		block(":root", staticVars),
		themeCss(first, true),
		...rest.map((t) => themeCss(t, false)),
		":root {\n\tcolor-scheme: light;\n}\n\n.dark {\n\tcolor-scheme: dark;\n}",
	].join("\n\n");
}

/** Tailwind v4 `@theme inline` that maps utilities (bg-primary, rounded-lg, ease-pop) onto the tokens. */
export function toTailwindTheme() {
	const colors = Object.keys(themes.pop.light)
		.map((k) => `\t--color-${k}: var(--zupy-${k});`)
		.join("\n");
	const radii = ["sm", "md", "lg", "xl"]
		.map((k) => `\t--radius-${k}: var(--zupy-radius-${k});`)
		.join("\n");
	const eases = Object.keys(easing)
		.map((k) => `\t--ease-${k}: var(--zupy-ease-${k});`)
		.join("\n");
	const fonts = Object.keys(font)
		.map((k) => `\t--font-${k}: var(--zupy-font-${k});`)
		.join("\n");
	return `/* Generated by @zupy/tokens. Do not edit. */\n@theme inline {\n${colors}\n${radii}\n${eases}\n${fonts}\n}\n`;
}
